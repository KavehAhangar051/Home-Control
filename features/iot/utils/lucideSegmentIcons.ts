function wrapLucideSegmentIcon(Icon: LucideIcon, displayName: string): HugeIconComponent {
  const Wrapped = ({
    size = 24,
    strokeWidth = 1.75,
    color,
    className = "",
    animateOnHover: _animateOnHover,
    animate: _animate,
    ref,
    "aria-hidden": ariaHidden,
    "aria-label": ariaLabel,
    role,
  }: HugeIconProps) => {
    return React.createElement(Icon, {
      ref,
      size: Number(size) || 24,
      strokeWidth,
      ...(color !== undefined ? { color } : {}),
      className,
      ...(typeof ariaHidden === "boolean" || ariaHidden === "true" || ariaHidden === "false"
        ? { "aria-hidden": ariaHidden }
        : {}),
      ...(typeof ariaLabel === "string" ? { "aria-label": ariaLabel } : {}),
      ...(typeof role === "string" ? { role } : {}),
    });
  };

  Wrapped.displayName = `LucideSegmentIcon(${displayName})`;
  return React.memo(Wrapped);
}

